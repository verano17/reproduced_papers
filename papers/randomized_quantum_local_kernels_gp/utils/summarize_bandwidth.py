"""Characterization summary of the encoding-bandwidth diagnostic (S8 vs S7).

Pre-declared in the LOG.md amendment of 2026-11-19T16:00:08Z: S8 (qubit,
exact features, L-BFGS, inputs × 2.5 before encoding) on data seeds
{12345, 1, 2, 3, 4} × Sobol seed 12345, compared with S7 (same, input scale
1.0) on the same seed pairs. C2 (RFF dictionary) and C5 (true-family GP) on
the same data are shown as context only. This is a CHARACTERIZATION: an
encoding the paper did not use, with no advantage statement.

Usage:
    python utils/summarize_bandwidth.py --out results/s8_bandwidth_characterization.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

SWEEPS_DIR = Path(__file__).resolve().parents[1] / "outdir" / "sweeps"
KERNELS = ("rbf", "matern32", "nonstat_ls")
METRICS = ("rmse", "avg_nlpd", "alignment_centered", "noise_variance")
PAIRS = [(d, 12345) for d in (12345, 1, 2, 3, 4)]


def _load(sweep_id: str) -> dict:
    status = json.loads((SWEEPS_DIR / sweep_id / "sweep_status.json").read_text())
    if status["status"] != "COMPLETED":
        raise ValueError(f"{sweep_id} is not COMPLETED.")
    runs = {}
    for run in status["runs"]:
        key = (run["candidate"]["data_seed"], run["candidate"]["sobol_seed"])
        metrics = json.loads((SWEEPS_DIR / sweep_id / run["metrics_path"]).read_text())
        runs[key] = {
            k: (v["learned_mixture"] if "learned_mixture" in v else v["parametric_gp"])
            for k, v in metrics["kernels"].items()
        }
    missing = [p for p in PAIRS if p not in runs]
    if missing:
        raise ValueError(f"{sweep_id} lacks seed pairs {missing}.")
    return runs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    systems = {
        "S8 (inputs x2.5)": _load("S8_table1_exact_features_lbfgs_x2p5"),
        "S7 (paper encoding)": _load("S7_table1_exact_features_lbfgs"),
        "C2 RFF dictionary (context)": _load("C2_table1_classical_rff_lbfgs"),
        "C5 true-family GP (context)": _load("C5_table1_classical_gp_true"),
    }
    lines = [
        "# Encoding-bandwidth characterization (generated by utils/summarize_bandwidth.py)",
        "",
        "Label: characterization (not the paper's encoding; no advantage statement). "
        "Exact qubit features, converged L-BFGS MKL; 5 data seeds x Sobol seed 12345; "
        "mean ± sample std over the 5 runs.",
        "",
        "| Kernel | System | RMSE | Avg NLPD | Centered alignment | Fitted noise variance |",
        "|---|---|---|---|---|---|",
    ]
    for kernel in KERNELS:
        for name, runs in systems.items():
            cells = []
            for metric in METRICS:
                values = np.array([runs[p][kernel][metric] for p in PAIRS])
                cells.append(f"{values.mean():.4f} ± {values.std(ddof=1):.4f}")
            lines.append(f"| {kernel} | {name} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "Paired differences S8 − S7 (same 5 seed pairs):",
        "",
        "| Kernel | Δ RMSE | Δ NLPD | Δ alignment | runs with lower RMSE |",
        "|---|---|---|---|---|",
    ]
    for kernel in KERNELS:
        diffs = {
            metric: np.array(
                [
                    systems["S8 (inputs x2.5)"][p][kernel][metric]
                    - systems["S7 (paper encoding)"][p][kernel][metric]
                    for p in PAIRS
                ]
            )
            for metric in ("rmse", "avg_nlpd", "alignment_centered")
        }
        lines.append(
            f"| {kernel} | {diffs['rmse'].mean():+.4f} | {diffs['avg_nlpd'].mean():+.4f} | "
            f"{diffs['alignment_centered'].mean():+.4f} | {int(np.sum(diffs['rmse'] < 0))}/5 |"
        )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
